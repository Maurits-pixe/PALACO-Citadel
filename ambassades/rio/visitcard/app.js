const routeSteps = document.querySelectorAll('#contact-route-steps > li > details');
const showRouteExplanation = (target) => {
  if (target.matches('details')) target.open = true;
  const heading = target.matches('details') ? target.querySelector('summary') : target;
  heading.focus({ preventScroll: true });
  heading.scrollIntoView({ block: 'start', behavior: 'instant' });
};
routeSteps.forEach((step, index) => {
  step.id = `contact-route-step-${index + 1}`;
});
const createRouteLink = (step) => {
  const link = document.createElement('a');
  link.href = `#${step.id}`;
  link.addEventListener('click', (event) => {
    if (window.location.hash !== link.hash) return;
    if (event.button !== 0 || event.ctrlKey || event.metaKey || event.shiftKey || event.altKey) return;
    event.preventDefault();
    showRouteExplanation(step);
  });
  return link;
};
routeSteps.forEach((step, index) => {
  const item = document.createElement('li');
  const overviewLink = createRouteLink(step);
  overviewLink.textContent = step.querySelector('summary').textContent;
  item.append(overviewLink);
  document.querySelector('#contact-route-links').append(item);
  const controls = document.createElement('div');
  controls.className = 'contact-route-reading';
  const addReadingButton = (key, target) => {
    const button = document.createElement('button');
    button.type = 'button';
    button.dataset.routeI18n = key;
    button.setAttribute('aria-controls', target.id);
    button.addEventListener('click', () => {
      step.open = false;
      showRouteExplanation(target);
    });
    controls.append(button);
  };
  if (index > 0) addReadingButton('previousExplanation', routeSteps[index - 1]);
  if (index < routeSteps.length - 1) {
    addReadingButton('nextExplanation', routeSteps[index + 1]);
  } else {
    addReadingButton('readSources', document.querySelector('#contact-route-sources'));
  }
  const permalink = createRouteLink(step);
  permalink.dataset.routeI18n = 'explanationLink';
  controls.append(permalink);
  step.append(controls);
});
const routeOverviewTitle = document.querySelector('#contact-route-overview-title');
const routeSources = document.querySelector('#contact-route-sources');
[...routeSteps, routeSources].forEach((step) => {
  let controls = step.querySelector('.contact-route-reading');
  if (!controls) {
    controls = document.createElement('div');
    controls.className = 'contact-route-reading';
    step.append(controls);
  }
  const overviewLink = createRouteLink(routeOverviewTitle);
  overviewLink.dataset.routeI18n = 'backToOverview';
  controls.append(overviewLink);
});
const revealLinkedRouteExplanation = () => {
  const target = [...routeSteps, routeSources, routeOverviewTitle]
    .find((step) => `#${step.id}` === window.location.hash);
  if (target) showRouteExplanation(target);
};
window.addEventListener('hashchange', revealLinkedRouteExplanation);
window.addEventListener('load', () => {
  requestAnimationFrame(revealLinkedRouteExplanation);
}, { once: true });
document.querySelector('#contact-route-start').addEventListener('click', () => {
  showRouteExplanation(routeSteps[0]);
});
document.querySelector('#contact-route-open').addEventListener('click', () => {
  routeSteps.forEach((step) => { step.open = true; });
});
document.querySelector('#contact-route-close').addEventListener('click', () => {
  routeSteps.forEach((step) => { step.open = false; });
});
document.querySelector('#contact-route-controls').hidden = false;
document.querySelector('#contact-route-overview').hidden = false;

