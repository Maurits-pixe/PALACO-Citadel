form?.addEventListener("submit", (event) => {
  event.preventDefault();
  inputErrorKey = input.value.length > input.maxLength ? "longMessage" : input.value.trim() ? undefined : "emptyMessage";
  updateComposer();
  if (inputErrorKey) {
    input.focus();
    return;
  }
  sendMessage(input.value);
  form.reset();
  updateComposer();
  input.focus();
});

