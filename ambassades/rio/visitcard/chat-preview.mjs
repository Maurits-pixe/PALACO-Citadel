const clearSubject = () => {
  selectedSubject = undefined;
  subjectContext.hidden = true;
  subjectContext.open = false;
  subjectContext.querySelectorAll("p, dd, strong").forEach((element) => {
    element.textContent = "";
  });
  subjectPrompt.hidden = true;
  followups.hidden = true;
  followups.open = false;
  followupTitle.textContent = "";
  followupButtons.replaceChildren();
  window.dispatchEvent(new CustomEvent("rio:subjectclear"));
};

window.addEventListener("rio:subjectchange", (event) => {
  const { openChat: shouldOpen, ...subject } = event.detail;
  const changed = selectedSubject?.id !== subject.id;
  selectedSubject = subject;
  for (const key of ["title", "description", "source", "status", "boundary"]) {
    const field = key === "status" ? "state" : key;
    document.querySelector(`#chat-preview-subject-${field}`).textContent = selectedSubject[key];
  }
  followupTitle.textContent = selectedSubject.followupTitle;
  followupButtons.replaceChildren();
  selectedSubject.questions.forEach((question) => {
    const button = document.createElement("button");
    button.type = "button";
    button.dataset.chatFollowup = question.id;
    button.textContent = question.label;
    button.addEventListener("click", () => {
      followups.open = false;
      subjectContext.open = false;
      followupTitle.focus({ preventScroll: true });
      sendMessage(question.label, question.id);
      messages.scrollIntoView({ block: "nearest" });
    });
    followupButtons.append(button);
  });
  followups.hidden = selectedSubject.questions.length === 0;
  subjectContext.hidden = false;
  subjectPrompt.hidden = false;
  if (changed) {
    subjectContext.open = false;
    followups.open = false;
  }
  if (shouldOpen) {
    status.textContent = "";
    openChat();
  }
});

