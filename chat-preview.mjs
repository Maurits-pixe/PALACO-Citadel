const toggle = document.querySelector("#chat-preview-toggle");
const panel = document.querySelector("#chat-preview-panel");
const closeButton = document.querySelector("#chat-preview-close");
const form = document.querySelector("#chat-preview-form");
const input = document.querySelector("#chat-preview-input");
const messages = document.querySelector("#chat-preview-messages");
const status = document.querySelector("#chat-preview-status");
const languageButtons = document.querySelectorAll(".lang-btn");

let language = document.documentElement.lang in copy ? document.documentElement.lang : "nl";
let strings = copy[language];

const updateCopy = () => {
  language = document.documentElement.lang in copy ? document.documentElement.lang : "nl";
  strings = copy[language];
  document.querySelectorAll("[data-chat-i18n]").forEach((element) => {
    element.textContent = strings[element.dataset.chatI18n];
  });
  document.querySelectorAll("[data-chat-i18n-placeholder]").forEach((element) => {
    element.placeholder = strings[element.dataset.chatI18nPlaceholder];
  });
  document.querySelectorAll("[data-chat-i18n-aria-label]").forEach((element) => {
    element.setAttribute("aria-label", strings[element.dataset.chatI18nAriaLabel]);
  });
};

const appendMessage = (author, body, kind) => {
  const item = document.createElement("li");
  item.className = `chat-preview-message is-${kind}`;
  const name = document.createElement("strong");
  name.textContent = author;
  const text = document.createElement("p");
  text.textContent = body;
  item.append(name, text);
  messages.append(item);
  item.scrollIntoView({ block: "nearest" });
};

const addWelcome = () => appendMessage(strings.rio, strings.welcome, "rio");

const answerFor = (message, prompt) => {
  if (prompt === "about") return strings.aboutAnswer;
  if (prompt === "privacy") return strings.privacyAnswer;
  const normalized = message.normalize("NFD").replace(/\p{Diacritic}/gu, "").toLocaleLowerCase();
  if (/\b(rio|what|who|wat|wie|was|qu|que|que es|que c'est|qui|was ist)\b|ما هو|是什么/u.test(normalized)) {
    return strings.aboutAnswer;
  }
  if (/\b(privacy|privacidad|datenschutz|confidentialite|confidentialidad|gegevens|privé|data|message|messages|bericht|berichten)\b|بيانات|رسائلي|隐私|消息/u.test(normalized)) {
    return strings.privacyAnswer;
  }
  return strings.otherAnswer;
};

const sendMessage = (message, prompt) => {
  const body = message.trim();
  if (!body) return;
  status.textContent = "";
  appendMessage(strings.visitor, body, "visitor");
  appendMessage(strings.rio, answerFor(body, prompt), "rio");
};

toggle?.addEventListener("click", () => {
  const open = panel.hidden;
  panel.hidden = !open;
  toggle.setAttribute("aria-expanded", String(open));
  if (open) input.focus();
  else toggle.focus();
});

closeButton?.addEventListener("click", () => {
  panel.hidden = true;
  toggle.setAttribute("aria-expanded", "false");
  toggle.focus();
});

document.addEventListener("keydown", (event) => {
  if (event.key !== "Escape" || panel.hidden) return;
  panel.hidden = true;
  toggle.setAttribute("aria-expanded", "false");
  toggle.focus();
});

form?.addEventListener("submit", (event) => {
  event.preventDefault();
  sendMessage(input.value);
  form.reset();
  input.focus();
});

document.querySelectorAll("[data-chat-prompt]").forEach((button) => {
  button.addEventListener("click", () => sendMessage(button.textContent, button.dataset.chatPrompt));
});

document.querySelector("#chat-preview-clear")?.addEventListener("click", () => {
  messages.replaceChildren();
  addWelcome();
  status.textContent = strings.cleared;
  input.focus();
});

document.addEventListener("rio:languagechange", updateCopy);
languageButtons.forEach((button) => button.addEventListener("click", updateCopy));
updateCopy();
addWelcome();
