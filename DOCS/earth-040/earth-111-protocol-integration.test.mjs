import assert from 'node:assert/strict';
import {generateKeyPairSync,sign,createHash} from 'node:crypto';
import {appendReviewRecord} from './earth-085-review-chain.mjs';
import {verifySignedAuditEvidence} from './earth-108-signed-evidence.mjs';
import {signatureMessage,EARTH110_PROTOCOL} from './earth-110-signature-envelope.mjs';
const {privateKey,publicKey}=generateKeyPairSync('ed25519');
const reviewerId='reviewer-key-1';
const payload={protocol:'EARTH-084-v1',sourceSHA256:null,outputSHA256:null,reviewerId,trustedEpoch:1,minimumAcceptedEpoch:1,status:'HOLD',stage:'REVIEW',reasons:['NOT_ADMITTED']};
const receipt={...payload,receiptSHA256:createHash('sha256').update(JSON.stringify(payload)).digest('hex')};
const record=appendReviewRecord([],receipt),checkpoint={length:1,headHash:record.recordHash};
const signature=sign(null,signatureMessage(receipt.receiptSHA256),privateKey).toString('base64');
const envelope={protocol:EARTH110_PROTOCOL,keyId:reviewerId,signature};
const base={chain:[record],receipts:[receipt],signatures:[envelope],trustAnchors:new Map([[reviewerId,publicKey.export({type:'spki',format:'pem'})]]),revokedReviewers:new Set(),revokedKeys:new Set(),checkpoint,trustedFloor:checkpoint,trustedEpoch:1,minimumAcceptedEpoch:1,signatureProtocol:'EARTH_110_V1'};
assert.equal(verifySignedAuditEvidence(base).status,'CRYPTOGRAPHIC_EVIDENCE_MATCH');
assert.equal(verifySignedAuditEvidence({...base,signatureProtocol:'LEGACY_V1'}).status,'HOLD');
assert.equal(verifySignedAuditEvidence({...base,revokedKeys:new Set([reviewerId])}).status,'HOLD');
assert.equal(verifySignedAuditEvidence({...base,signatures:[{...envelope,keyId:'other'}]}).status,'HOLD');
assert.equal(verifySignedAuditEvidence({...base,signatures:[sign(null,Buffer.from(receipt.receiptSHA256,'hex'),privateKey).toString('base64')]}).status,'HOLD');
console.log('EARTH-111 protocol separation integration PASS');
