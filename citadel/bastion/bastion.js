const tasks = [
  { id: 'task1', group: 'group1', priority: 'priorityHigh', status: 'active' },
  { id: 'task2', group: 'group2', priority: 'priorityMedium', status: 'watch' },
  { id: 'task3', group: 'group3', priority: 'priorityLow', status: 'done' },
  { id: 'task4', group: 'group4', priority: 'priorityMedium', status: 'active' }
];

const personnel = [
  { name: 'person1', role: 'role1', presence: 'presence1', state: 'online' },
  { name: 'person2', role: 'role2', presence: 'presence2', state: 'mission' },
  { name: 'person3', role: 'role3', presence: 'presence3', state: 'online' },
  { name: 'person4', role: 'role4', presence: 'presence4', state: 'offline' }
];

const taskList = document.querySelector('#task-list');
const personnelList = document.querySelector('#personnel-list');
const messageList = document.querySelector('#message-list');
const messageEmpty = document.querySelector('#message-empty');
const messageStatus = document.querySelector('#message-status');
const messageForm = document.querySelector('#message-form');
const messageInput = document.querySelector('#message-input');
const languageSelect = document.querySelector('#language-select');
const activeMessages = new Map();
let language = 'en';
let nextMessageId = 0;

const translate = (key) => messages[language]?.[key] ?? messages.en[key] ?? key;

function textElement(tag, className, text) {
  const element = document.createElement(tag);
  if (className) element.className = className;
  element.textContent = text;
  return element;
}

function renderTasks() {
  taskList.replaceChildren();
  for (const task of tasks) {
    const item = document.createElement('li');
    item.className = 'task-item';
    const details = document.createElement('div');
    details.append(
      textElement('h3', 'task-title', translate(task.id))
    );
    const meta = textElement('div', 'task-meta', '');
    const group = textElement('span', '', translate(task.group));
    const priority = textElement('span', 'priority', translate(task.priority));
    const status = textElement('span', `task-status status-${task.status}`, translate(`status${task.status[0].toUpperCase()}${task.status.slice(1)}`));
    meta.append(group, priority, status);
    details.append(meta);
    const action = textElement('button', `task-action${task.status === 'done' ? ' is-done' : ''}`,
      translate(task.status === 'done' ? 'taskReopen' : 'taskComplete'));
    action.type = 'button';
    action.setAttribute('aria-pressed', String(task.status === 'done'));
    action.setAttribute('aria-label', `${action.textContent}: ${translate(task.id)}`);
    action.addEventListener('click', () => {
      task.status = task.status === 'done' ? 'active' : 'done';
      renderTasks();
    });
    item.append(details, action);
    taskList.append(item);
  }
}

function renderPersonnel() {
  personnelList.replaceChildren();
  personnel.forEach((member, index) => {
    const item = document.createElement('li');
    item.className = 'personnel-item';
    item.append(textElement('span', 'personnel-mark', `0${index + 1}`));
    const info = document.createElement('div');
    info.append(
      textElement('p', 'personnel-name', translate(member.name)),
      textElement('p', 'personnel-role', translate(member.role))
    );
    const presence = textElement('span', `presence ${member.state}`, '');
    presence.append(
      Object.assign(document.createElement('span'), { className: 'status-dot', ariaHidden: 'true' }),
      textElement('span', '', translate(member.presence))
    );
    item.append(info, presence);
    personnelList.append(item);
  });
}

function formatRemaining(milliseconds) {
  const seconds = Math.max(0, Math.ceil(milliseconds / 1000));
  return `00:${String(seconds).padStart(2, '0')}`;
}

function renderMessages() {
  const now = Date.now();
  let expiredAny = false;
  for (const [id, message] of activeMessages) {
    if (now >= message.expiresAt) {
      activeMessages.delete(id);
      expiredAny = true;
    }
  }
  messageList.replaceChildren();
  messageEmpty.hidden = activeMessages.size > 0;
  for (const message of activeMessages.values()) {
    const item = document.createElement('li');
    item.className = 'message-item';
    const top = textElement('div', 'message-topline', '');
    top.append(
      textElement('span', '', translate('sender')),
      Object.assign(textElement('span', 'message-expiry',
        translate('expiresIn').replace('{time}', formatRemaining(message.expiresAt - now))), {
        ariaHidden: 'true'
      })
    );
    item.append(top, textElement('p', 'message-text', message.text));
    messageList.append(item);
  }
  if (expiredAny) messageStatus.textContent = translate('messageExpired');
}

function setLanguage(nextLanguage) {
  language = Object.hasOwn(messages, nextLanguage) ? nextLanguage : 'en';
  const copy = messages[language];
  document.documentElement.lang = language;
  document.documentElement.dir = language === 'ar' ? 'rtl' : 'ltr';
  document.title = copy.title;
  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const key = element.dataset.i18n;
    if (copy[key]) element.textContent = copy[key];
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
    const key = element.dataset.i18nPlaceholder;
    if (copy[key]) element.placeholder = copy[key];
  });
  languageSelect.value = language;
  renderTasks();
  renderPersonnel();
  renderMessages();
  try {
    localStorage.setItem('palaco-language', language);
  } catch {
    // Language selection remains usable when browser storage is unavailable.
  }
}

messageForm.addEventListener('submit', (event) => {
  event.preventDefault();
  const text = messageInput.value.trim();
  if (!text) return;
  activeMessages.set(`demo-${++nextMessageId}`, { text, expiresAt: Date.now() + 30_000 });
  messageInput.value = '';
  messageStatus.textContent = translate('messageSent');
  renderMessages();
  messageInput.focus();
});

languageSelect.addEventListener('change', () => setLanguage(languageSelect.value));
setInterval(renderMessages, 1000);
let savedLanguage = 'en';
try {
  savedLanguage = localStorage.getItem('palaco-language') || 'en';
} catch {
  // Fall back to English when browser storage is unavailable.
}
setLanguage(savedLanguage);
